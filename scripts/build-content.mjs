import {readFile,mkdir,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve,relative} from 'node:path';
import {assertValidCourses} from './content-contract.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
export async function readContent(directory=resolve(root,'content')){
 const catalog=JSON.parse(await readFile(resolve(directory,'catalog.json'),'utf8'));
 if(catalog.schemaVersion!==1||!Array.isArray(catalog.courses)||!catalog.courses.length||Object.keys(catalog).some(k=>!['schemaVersion','courses'].includes(k)))throw new Error('catalog.json 格式錯誤');
 if(new Set(catalog.courses).size!==catalog.courses.length)throw new Error('catalog.json 有重複檔案');
 const courses=[];for(const name of catalog.courses){if(typeof name!=='string'||!/^courses\/[a-z0-9-]+\.json$/.test(name))throw new Error('課程路徑格式錯誤');const course=JSON.parse(await readFile(resolve(directory,name),'utf8'));if(name!==`courses/${course.id}.json`)throw new Error(`檔名與課程 ID 不一致：${name}`);courses.push(course);}return assertValidCourses(courses);
}
export async function buildContent(){
 const courses=await readContent();const destination=resolve(root,'dist/content');await mkdir(destination,{recursive:true});
 // One generated module; no runtime network request or hand-maintained JS copy.
 await writeFile(resolve(destination,'published.js'),'// Generated by scripts/build-content.mjs; edit content/courses/*.json instead.\nexport const CONTENT='+JSON.stringify(courses)+';\n');
 console.log(`PASS: ${courses.length} 堂課／${courses.reduce((n,c)=>n+c.scenarios.length,0)} 個情境資料檢查及產出完成`);
}
if(process.argv[1]&&relative(resolve(process.argv[1]),fileURLToPath(import.meta.url))==='')await buildContent();
