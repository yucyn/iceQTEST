import assert from 'node:assert/strict';
import {transformBoardView,bindBoardViewport} from '../dist/board-viewport.js';
const base={x:0,y:0,w:1000,h:600};
const camera=transformBoardView(base,base,{x:500,y:300},{x:500,y:300},2);
assert.deepEqual(camera,{x:250,y:150,w:500,h:300});
assert.deepEqual(transformBoardView(base,base,{x:500,y:300},{x:500,y:300},100),{x:375,y:225,w:250,h:150});
assert.equal(transformBoardView(camera,base,{x:500,y:300},{x:600,y:300},1).x,150,'fingers moving right pan rink right');
assert.deepEqual(transformBoardView(camera,base,{x:500,y:300},{x:500,y:300},.01),base);
for(const x of [0,500]){const half={x,y:0,w:500,h:600};const zoom=transformBoardView(half,half,{x:x+250,y:300},{x:x+250,y:300},4);const pan=transformBoardView(zoom,half,{x:0,y:0},{x:-1e5,y:-1e5},1);assert.equal(pan.x,x+375);assert.equal(pan.y,450);}
const handlers=new Map(),eventRoot={addEventListener(n,fn){handlers.set(n,fn);},removeEventListener(n){handlers.delete(n);}};
let vb={...base},cancelled=0,zoomLabel=0;
const rink={contains:t=>t===rink,setAttribute(n,v){if(n==='viewBox'){const [x,y,w,h]=v.split(' ').map(Number);vb={x,y,w,h};}},dispatchEvent(e){assert.equal(e.type,'pointercancel');cancelled++;},getScreenCTM(){return {inverse:()=>null};},createSVGPoint(){return {x:0,y:0,matrixTransform(){return {x:vb.x+this.x*vb.w/1000,y:vb.y+this.y*vb.h/600};}};}};
const controller=bindBoardViewport(rink,{enabled:()=>true,eventRoot,onChange:z=>zoomLabel=z});
const emit=(name,id,x,y,extra={})=>{const e={target:rink,pointerId:id,clientX:x,clientY:y,pointerType:'touch',blocked:false,preventDefault(){},stopImmediatePropagation(){this.blocked=true;},...extra};handlers.get(name)?.(e);return e;};
assert.equal(emit('pointerdown',1,400,300).blocked,false);
assert.equal(emit('pointerdown',2,600,300).blocked,true);assert.equal(cancelled,1);
emit('pointermove',2,800,300);assert.equal(vb.w,500);assert.equal(zoomLabel,2);
emit('pointermove',1,500,300);assert.ok(vb.w>500);
emit('pointerdown',3,900,300);const frozen={...vb};emit('pointermove',3,950,300);assert.deepEqual(vb,frozen);
emit('pointercancel',3,950,300);emit('pointerup',2,800,300);
assert.equal(emit('pointermove',1,600,400).blocked,true,'remaining finger cannot draw');
assert.equal(emit('pointerup',1,600,400).blocked,true);
assert.equal(emit('click',1,600,400).blocked,true,'synthetic tap cannot place player');
assert.equal(emit('pointerdown',4,100,100,{pointerType:'pen'}).blocked,false);
assert.equal(emit('pointerdown',5,100,100,{target:{}}).blocked,false);
controller.reset();assert.deepEqual(vb,base);assert.equal(zoomLabel,1);
assert.equal(emit('pointerdown',6,100,100).blocked,false);emit('blur');assert.equal(emit('pointerdown',7,200,200).blocked,false);
controller.destroy();assert.equal(handlers.size,0);
console.log('PASS: 2D camera anchors/bounds, half views, pointer gate, cancellation, click suppression, remaining/third finger and cleanup.');
